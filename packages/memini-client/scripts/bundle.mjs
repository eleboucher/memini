#!/usr/bin/env node
// Bundle @memini/client into the single dependency-free ESM file the Claude Code
// and Codex hooks import: plugin/scripts/_client.gen.mjs.
//
// Why a committed artifact rather than a normal dependency: the plugin ships as
// RAW FILES. Claude Code copies plugin/ into its cache and runs the scripts with
// a bare `node` — there is no install step, no node_modules, no build. That is
// the same constraint that made the hooks .mjs instead of .ts in the first
// place. So the TypeScript is the source of truth, and the bundle is generated
// from it and checked in, with `mise run client-check` failing CI on drift —
// exactly how docs/reference/ is already handled in this repo.

import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, "..");
const outfile = path.resolve(pkgRoot, "../../plugin/scripts/_client.gen.mjs");

const banner = `// Code generated by packages/memini-client. DO NOT EDIT.
//
// Regenerate with:  mise run build-client
// CI fails on drift via:  mise run client-check
//
// Source of truth: packages/memini-client/src/*.ts
// This file is committed because the plugin ships as raw files with no
// install-time build step — the hooks run under a bare \`node\`.`;

await build({
  entryPoints: [path.join(pkgRoot, "src/index.ts")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  // Node builtins stay external; the package has no other runtime dependencies,
  // so the output is self-contained.
  packages: "external",
  banner: { js: banner },
  // Readable output: this file gets read by humans debugging a namespace
  // mismatch, and a minified blob would defeat the purpose.
  minify: false,
  legalComments: "none",
});

console.log(`memini-client -> ${path.relative(path.resolve(pkgRoot, "../.."), outfile)}`);
